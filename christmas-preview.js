export function makeChristmasPreview(input) {
  const chance = wishChance(input);
  const scene = scenes[input.wish];
  const [title, story, chanceReason] = scene[chanceTier(chance)];
  return {...input, title, story, chance, chanceReason, wishLabel: wishes[input.wish].label,
    art: scene.art, artLabel: sceneLabels[scene.art], isPreview: true};
}
